-- =========================================================
-- Этап 24: признак упражнения «можно выполнять с личным весом».
-- Для таких упражнений тоннаж = (свой вес + отягощение) × повторения; для остальных — вес × повторения.
-- Меняется в приложении: Настройки → Управление упражнениями (админ — все, пользователь — свои).
-- SQL Editor → Run. Повторный запуск безопасен (не перезаписывает то, что уже отмечено вручную).
-- =========================================================
alter table exercises add column if not exists bodyweight boolean;

-- базовые упражнения со своим весом (только там, где признак ещё не задан)
update exercises set bodyweight = true
where bodyweight is null and type not in ('cardio','stretch') and (
  name ~* '(подтяг|отжим|брус|выход силой|переворот|пистолет|свой вес|австрал|планк|уголок|вис\M|флаж|планш|бёрпи|берпи|выпрыгив|подъём ног в висе)'
  or name ~* '(стойк.*рук)');
update exercises set bodyweight = false where bodyweight is null;

-- проверка: упражнения со своим весом
select name, bodyweight from exercises where owner_id is null and bodyweight order by name;
