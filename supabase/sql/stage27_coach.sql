-- =========================================================
-- Этап 27: упрощённый режим тренировки для новичков.
-- Уровень (новичок / есть опыт / продвинутый), выбранная программа, акцентные группы и переключатель
-- «минималистичный режим» хранятся в профиле — чтобы были одинаковыми на телефоне и компьютере.
-- Повторный запуск безопасен.
-- =========================================================
alter table profiles add column if not exists coach jsonb;

select count(*) filter (where coach is not null) as "настроили режим", count(*) as "всего профилей" from profiles;
